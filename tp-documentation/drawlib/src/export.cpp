#include <drawlib/export.hpp>

#include <fstream>
#include <iostream>

bool Export::pnm(const Image & image, const std::string & filename) {

  try {
    std::ofstream ofs(filename);
    ofs << "P2" << std::endl;
    ofs << "# generated by drawlib" << std::endl;
    ofs << image.width() << " " << image.height() << std::endl;
    ofs << "255" << std::endl;
    for (int y=0; y<image.height(); y++) {
      for (int x=0; x<image.width(); x++) {
        const int v = image.getPixel(x, y);
        ofs << v << " ";
      }
      ofs << std::endl;
    }
  }
  catch (const std::exception & e) {
    std::cerr << "error: " << e.what() << std::endl;
    return false;
  }
  catch (...) {
    std::cerr << "unknown error" << std::endl;
    return false;
  }

  return true;
}

